#!/usr/bin/env python3
"""
i18n.py — MintQMS interface translations.

Source of truth:  Resources/Localization/translations.json
    { "Back to List": {"es": "Volver a la lista", "pt-BR": "Voltar à lista", "note": "optional"}, ... }
    The key is the English text exactly as the code shows it. A key with no translation
    is shown in English, so the screen never breaks.

Generated (never edit by hand, commit them):
    Resources/Localization/SharedResource.es.resx
    Resources/Localization/SharedResource.pt-BR.resx

Commands:
    tools/i18n.py build            write the .resx files from translations.json
    tools/i18n.py check            fail on: .resx out of date; a used key missing or untranslated;
                                   placeholders ({0}, {1}…) that differ from the English; HTML in a
                                   translation; leading/trailing space differences. Lists unused keys.
    tools/i18n.py report           coverage: keys used in code, translated, missing
    tools/i18n.py review [out.csv] review sheet (key, es, pt-BR, note, where used) for a native reader
    tools/i18n.py missing          the used keys that have no entry yet (to add to translations.json)

Keys "used in code" are: L["…"] literals in .cshtml/.cs, plus every enum value's English display
name (as EnumHelper.Display makes it) and the role names (EnumHelper.RoleName), because views show
them through L.Enum / L.Role.
"""
import csv, glob, json, os, re, sys
from xml.sax.saxutils import escape

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "Resources", "Localization", "translations.json")
LANGS = ["es", "pt-BR"]
RESX = {l: os.path.join(ROOT, "Resources", "Localization", f"SharedResource.{l}.resx") for l in LANGS}

RESX_HEAD = """<?xml version="1.0" encoding="utf-8"?>
<!-- GENERATED by tools/i18n.py from translations.json — do not edit by hand. -->
<root>
  <resheader name="resmimetype"><value>text/microsoft-resx</value></resheader>
  <resheader name="version"><value>2.0</value></resheader>
  <resheader name="reader"><value>System.Resources.ResXResourceReader, System.Windows.Forms, Version=4.0.0.0, Culture=neutral, PublicKeyToken=b77a5c561934e089</value></resheader>
  <resheader name="writer"><value>System.Resources.ResXResourceWriter, System.Windows.Forms, Version=4.0.0.0, Culture=neutral, PublicKeyToken=b77a5c561934e089</value></resheader>
"""

# --- keys used in code -------------------------------------------------------------------------
L_LITERAL = re.compile(r'(?:\b[LHl]\[|\b_l\[|\bStatusMessage\s*=\s*\$?(?=")|\bthis\.T\(|\bT\(base\.\w+\([^)]*\),)\s*"((?:[^"\\]|\\.)*)"\s*[\]),;]')


def unescape_cs(s):
    return s.replace('\\"', '"').replace("\\\\", "\\")


def code_files():
    for pat in ("Views/**/*.cshtml", "Areas/**/*.cshtml", "Controllers/**/*.cs", "Services/**/*.cs",
                "Areas/**/*.cs", "Localization/**/*.cs", "Middleware/**/*.cs", "Authorization/**/*.cs"):
        yield from glob.glob(os.path.join(ROOT, pat), recursive=True)


def literal_keys():
    used = {}
    for f in code_files():
        text = open(f, encoding="utf-8-sig", errors="replace").read()
        text = re.sub(r"@\*.*?\*@|/\*.*?\*/", "", text, flags=re.S)       # Razor and block comments
        text = re.sub(r"(?m)^\s*//.*$", "", text)                             # whole-line // and /// comments
        for m in L_LITERAL.finditer(text):
            used.setdefault(unescape_cs(m.group(1)), set()).add(os.path.relpath(f, ROOT))
    return used


def enum_keys():
    """English display names of every enum value, computed exactly like EnumHelper.Display."""
    used = {}
    for f in glob.glob(os.path.join(ROOT, "Models", "**", "*.cs"), recursive=True):
        text = open(f, encoding="utf-8-sig", errors="replace").read()
        for m in re.finditer(r"public enum (\w+)\s*(?::\s*\w+\s*)?\{(.*?)\}", text, re.S):
            body = re.sub(r"//[^\n]*|/\*.*?\*/", "", m.group(2), flags=re.S)
            for item in re.finditer(r"((?:\[[^\]]*\]\s*)*)\s*([A-Za-z_]\w*)\s*(?:=\s*[^,]+)?\s*(?:,|$)", body):
                attrs, name = item.group(1), item.group(2)
                dm = re.search(r'Display\s*\([^)]*Name\s*=\s*"((?:[^"\\]|\\.)*)"', attrs)
                disp = unescape_cs(dm.group(1)) if dm else re.sub(r"(?<=[a-z])(?=[A-Z])", " ", name)
                used.setdefault(disp, set()).add(f"enum {m.group(1)}")
    return used


def role_keys():
    used = {}
    consts = os.path.join(ROOT, "Authorization", "Constants.cs")
    if os.path.exists(consts):
        for m in re.finditer(r'Role\s*=\s*"(\w+)"', open(consts, encoding="utf-8-sig").read()):
            used.setdefault(re.sub(r"(?<=[a-z])(?=[A-Z])", " ", m.group(1)), set()).add("role")
    return used


def display_keys():
    """[Display(Name = "…")] on model and page-model properties (labels, translated automatically)."""
    used = {}
    for pat in ("Models/**/*.cs", "ViewModels/**/*.cs", "Areas/**/*.cs"):
        for f in glob.glob(os.path.join(ROOT, pat), recursive=True):
            text = open(f, encoding="utf-8-sig", errors="replace").read()
            for m in re.finditer(r'\[Display\([^)]*Name\s*=\s*"((?:[^"\\]|\\.)*)"[^\]]*\]\s*(?:\[[^\]]*\]\s*)*public\s', text):
                used.setdefault(unescape_cs(m.group(1)), set()).add("label " + os.path.relpath(f, ROOT))
    return used


# Framework validation templates, read at runtime by Localization/ValidationMessages.cs (System.SR).
FRAMEWORK_KEYS = [
    "The {0} field is required.",
    "The field {0} must be between {1} and {2}.",
    "The {0} field is not a valid e-mail address.",
    "The field {0} must be a string or array type with a maximum length of '{1}'.",
    "The {0} field is not a valid phone number.",
    "The field {0} must be a string with a maximum length of {1}.",
    "The field {0} must be a string with a minimum length of {2} and a maximum length of {1}.",
]


def used_keys():
    used = {k: {"framework validation template"} for k in FRAMEWORK_KEYS}
    for src in (literal_keys(), enum_keys(), role_keys(), display_keys()):
        for k, where in src.items():
            used.setdefault(k, set()).update(where)
    return used


# --- source and generated files ------------------------------------------------------------------
def load():
    return json.load(open(SRC, encoding="utf-8")) if os.path.exists(SRC) else {}


def save(data):
    os.makedirs(os.path.dirname(SRC), exist_ok=True)
    with open(SRC, "w", encoding="utf-8") as fh:
        json.dump(dict(sorted(data.items(), key=lambda kv: kv[0].lower())), fh, ensure_ascii=False, indent=1)
        fh.write("\n")


def render_resx(data, lang):
    out = [RESX_HEAD]
    seen = set()                     # the resource compiler is case-insensitive: one entry per case-variant
    for key in sorted(data, key=lambda k: (k.lower(), k)):
        if key.lower() in seen:
            continue
        seen.add(key.lower())
        val = (data[key] or {}).get(lang)
        if not val:
            continue
        out.append(f'  <data name="{escape(key, {chr(34): "&quot;"})}" xml:space="preserve"><value>{escape(val)}</value></data>\n')
    out.append("</root>\n")
    return "".join(out)


PLACEHOLDER = re.compile(r"\{\d+(?::[^}]*)?\}")


def problems(data, used):
    errs, warns = [], []
    for lang in LANGS:
        want = render_resx(data, lang)
        have = open(RESX[lang], encoding="utf-8").read() if os.path.exists(RESX[lang]) else ""
        if want != have:
            errs.append(f"{os.path.relpath(RESX[lang], ROOT)} is out of date — run tools/i18n.py build")
    groups = {}
    for key in data:
        groups.setdefault(key.lower(), []).append(key)
    for variants in groups.values():
        for lang in LANGS:
            vals = {(data[v] or {}).get(lang) for v in variants}
            if len(vals) > 1:
                errs.append(f"keys differing only in capitals must translate the same ({lang}): {variants}")
    for key, tr in data.items():
        for lang in LANGS:
            v = (tr or {}).get(lang)
            if not v:
                errs.append(f"untranslated ({lang}): {key!r}")
                continue
            if sorted(re.findall(r"_[A-Z]+_", key)) != sorted(re.findall(r"_[A-Z]+_", v)):
                errs.append(f"DataTables tokens differ ({lang}): {key!r} → {v!r}")
            if sorted(PLACEHOLDER.findall(key)) != sorted(PLACEHOLDER.findall(v)):
                errs.append(f"placeholders differ ({lang}): {key!r} → {v!r}")
            if re.search(r"<[a-zA-Z/]", v) and not re.search(r"<[a-zA-Z/]", key):
                errs.append(f"HTML in translation ({lang}): {key!r} → {v!r}")
            if key[:1].isspace() != v[:1].isspace() or key[-1:].isspace() != v[-1:].isspace():
                errs.append(f"leading/trailing space differs ({lang}): {key!r} → {v!r}")
    for key in sorted(set(data) - set(used)):
        warns.append(f"unused key (safe, but tidy up): {key!r}")
    return errs, warns


def main():
    cmd = sys.argv[1] if len(sys.argv) > 1 else "check"
    data = load()
    if cmd == "build":
        for lang in LANGS:
            with open(RESX[lang], "w", encoding="utf-8") as fh:
                fh.write(render_resx(data, lang))
        print(f"✓ wrote {len(LANGS)} .resx files from {len(data)} keys")
        return 0
    used = used_keys()
    if cmd == "check":
        errs, warns = problems(data, used)
        missing = sorted(k for k in used if k not in data and k.strip())
        lits = literal_keys()
        missing_lit = [k for k in missing if k in lits]   # written in code as L["…"] but no entry yet
        for w in warns:
            print("  · " + w)
        for k in missing_lit:
            errs.append(f"L[\"{k}\"] used in code but not in translations.json ({', '.join(sorted(lits[k]))[:120]})")
        for e in errs:
            print("✗ " + e)
        if errs:
            return 1
        print(f"✓ translations consistent — {len(data)} keys; labels, enum and role names not yet translated: "
              f"{len([k for k in missing if k not in lits])} (shown in English)")
        return 0
    if cmd == "report":
        lits = literal_keys()
        print(f"keys in code (L[\"…\"]): {len(lits)}; enum/role names: {len(set(used) - set(lits))}")
        print(f"translated: {len([k for k in used if k in data])} of {len(used)}")
        return 0
    if cmd == "missing":
        for k in sorted(k for k in used if k not in data and k.strip()):
            print(json.dumps(k, ensure_ascii=False), "  #", ", ".join(sorted(used[k]))[:100])
        return 0
    if cmd == "review":
        out = sys.argv[2] if len(sys.argv) > 2 else "translations-review.csv"
        with open(out, "w", newline="", encoding="utf-8-sig") as fh:
            w = csv.writer(fh)
            w.writerow(["English", "Español", "Português (Brasil)", "Note", "Where used"])
            for k in sorted(data, key=str.lower):
                t = data[k]
                w.writerow([k, t.get("es", ""), t.get("pt-BR", ""), t.get("note", ""), "; ".join(sorted(used.get(k, [])))[:200]])
        print(f"✓ review sheet: {out}")
        return 0
    print(__doc__)
    return 2


if __name__ == "__main__":
    sys.exit(main())
